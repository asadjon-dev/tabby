const i18nTextNodes = new WeakMap();
const i18nAttributes = new WeakMap();

function translateTextNode(node, dict) {
  if (!i18nTextNodes.has(node)) i18nTextNodes.set(node, node.nodeValue);
  const source = i18nTextNodes.get(node);
  const key = source.trim();
  const value = dict[key];
  if (!value) {
    if (node.nodeValue !== source) node.nodeValue = source;
    return;
  }
  const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\s+/g, '\\s+');
  node.nodeValue = source.replace(new RegExp(escaped), () => value);
}

function translateAttributes(element, dict) {
  ['placeholder', 'title', 'aria-label', 'data-tooltip'].forEach(attribute => {
    if (!element.hasAttribute(attribute)) return;
    let originals = i18nAttributes.get(element);
    if (!originals) {
      originals = {};
      i18nAttributes.set(element, originals);
    }
    if (!(attribute in originals)) originals[attribute] = element.getAttribute(attribute);
    const source = originals[attribute];
    const key = source.replace(/\s+/g, ' ').trim();
    element.setAttribute(attribute, dict[key] || source);
  });
}

function applyLanguage(language) {
  const dict = I18N[language] || {};
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      if (parent.closest('script, style, svg, #appTooltip')) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(node => translateTextNode(node, dict));
  document.querySelectorAll('[placeholder], [title], [aria-label], [data-tooltip]').forEach(element => {
    if (element.closest('svg')) return;
    translateAttributes(element, dict);
  });
}
